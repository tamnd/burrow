/* The testdata files in a new temporary directory, which the caller removes. */
static Str write_testdata(TestingT *t, Alloc *a) {
    Error err = BURROW_NO_ERROR;
    Str dir = os_mkdir_temp(a, BURROW_STR_EMPTY, BURROW_S("net-dns"), &err);
    if (BURROW_FAILED(err)) {
        testing_t_fatalf_v(t, "MkdirTemp: %v", err);
        return BURROW_STR_EMPTY;
    }
    for (size_t i = 0; i < sizeof test_files / sizeof test_files[0]; i++) {
        const TestFile *f = &test_files[i];
        Str name = path_join_v(a, 2, dir, str_from_cstr(f->name));
        Slice data = slice_from((void *)(uintptr_t)f->data, f->len, f->len, TYPE_BYTE);
        err = os_write_file(name, data, 0644);
        if (BURROW_FAILED(err)) {
            (void)os_remove_all(dir);
            testing_t_fatalf_v(t, "WriteFile: %v", err);
            return BURROW_STR_EMPTY;
        }
    }
    return dir;
}

static Str td(Alloc *a, Str dir, const char *name) {
    return path_join_v(a, 2, dir, str_from_cstr(name));
}

/* A slice of Str the way %v prints one in Go. */
static Str strs(Alloc *a, Slice s) {
    Str j = strings_join(a, s, BURROW_S(" "));
    Str out = strings_join(
        a, slice_from((Str[]){BURROW_S("["), j, BURROW_S("]")}, 3, 3, TYPE_STRING),
        BURROW_STR_EMPTY);
    return out;
}

static Slice cstrs(Alloc *a, const char *const *v, Int n) {
    Slice s = slice_make(a, TYPE_STRING, 0, n);
    for (Int i = 0; i < n; i++) {
        Str x = str_from_cstr(v[i]);
        s = slice_append(a, s, &x, 1);
    }
    return s;
}

static bool strs_eq(Slice x, Slice y) {
    if (x.len != y.len)
        return false;
    for (Int i = 0; i < x.len; i++)
        if (!str_eq(((const Str *)x.p)[i], ((const Str *)y.p)[i]))
            return false;
    return true;
}

static Str abs_name(Alloc *a, Str s) {
    return burrow__net_abs_domain_name(a, s);
}

