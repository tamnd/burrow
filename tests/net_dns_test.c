static void TestDNSName(TestingT *t) {
    static const struct {
        const char *name;
        bool result;
    } tests[] = {
        /* RFC 2181, section 11. */
        {"_xmpp-server._tcp.google.com", true},
        {"foo.com", true},
        {"1foo.com", true},
        {"26.0.0.73.com", true},
        {"10-0-0-1", true},
        {"fo-o.com", true},
        {"fo1o.com", true},
        {"foo1.com", true},
        {"a.b..com", false},
        {"a.b-.com", false},
        {"a.b.com-", false},
        {"a.b..", false},
        {"b.com.", true},
    };
    Arena ar;
    arena_init(&ar, NULL, 0);
    Alloc *a = arena_allocator(&ar);
    for (size_t k = 0; k < sizeof tests / sizeof tests[0]; k++) {
        Str name = str_from_cstr(tests[k].name);
        if (burrow__net_is_domain_name(name) != tests[k].result)
            testing_t_errorf_v(t, "isDomainName(%q) = %v; want %v", name,
                               !tests[k].result, tests[k].result);
    }

    Str char63 = strings_repeat(a, BURROW_S("a"), 63);
    Str char64 = cat2(a, char63, BURROW_S("a"));
    Str ld = long_domain(a);
    struct {
        Str name;
        bool result;
    } more[] = {
        {cat2(a, char63, BURROW_S(".com")), true},
        {cat2(a, char64, BURROW_S(".com")), false},
        /* Remember: wire format is two octets longer than presentation
         * (length octets for the first and [root] last labels). 253 is
         * fine: */
        {str_from_bytes(ld.p + ld.len - 253, 253), true},
        /* A terminal dot doesn't contribute to length: */
        {cat2(a, str_from_bytes(ld.p + ld.len - 253, 253), BURROW_S(".")), true},
        /* 254 is bad: */
        {str_from_bytes(ld.p + ld.len - 254, 254), false},
    };
    for (size_t k = 0; k < sizeof more / sizeof more[0]; k++)
        if (burrow__net_is_domain_name(more[k].name) != more[k].result)
            testing_t_errorf_v(t, "isDomainName(%q) = %v; want %v", more[k].name,
                               !more[k].result, more[k].result);
    arena_free(&ar);
}

