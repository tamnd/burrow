#!/bin/sh
# Regenerates src/html/entity.c, the named character references of package
# html, from Go's html/entity.go, so every name and code point is Go's. Go keeps
# them in two maps. This keeps them in two arrays sorted by name, for a binary
# search, with the same split: one code point in the first, two in the second.
#
# Reads $GOROOT/src/html/entity.go, with GOROOT from the environment or from
# the go on PATH, which should be the release the port follows.
#
# Copyright 2026 The burrow Authors. All rights reserved.
# Use of this source code is governed by a BSD-style licence that can be found
# in the LICENSE file.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
goroot=${GOROOT:-$(go env GOROOT)}
in="$goroot/src/html/entity.go"
out="$root/src/html/entity.c"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# One line per entity: the name, then its code points in hex.
sed -n 's/^[[:space:]]*"\([A-Za-z0-9;]*\)":[[:space:]]*'"'"'\\U\([0-9A-F]*\)'"'"',$/\1 \2/p' "$in" |
	LC_ALL=C sort > "$tmp/one"
sed -n 's/^[[:space:]]*"\([A-Za-z0-9;]*\)":[[:space:]]*{'"'"'\\u\([0-9A-F]*\)'"'"', '"'"'\\u\([0-9A-F]*\)'"'"'},$/\1 \2 \3/p' "$in" |
	LC_ALL=C sort > "$tmp/two"

# Every entity line has to have been read, or the tables are short.
want=$(grep -c '^[[:space:]]*"[A-Za-z0-9;]*":' "$in")
got=$(cat "$tmp/one" "$tmp/two" | wc -l | tr -d ' ')
if [ "$want" != "$got" ]; then
	printf 'gen-html-entity: read %s of the %s entities in %s\n' "$got" "$want" "$in" >&2
	exit 1
fi

{
	cat <<'EOF'
/* package html, the named character references. Generated by
 * tools/gen-html-entity.sh from Go's html/entity.go. Do not edit.
 *
 * Copyright 2010 The Go Authors. All rights reserved.
 * Copyright 2026 The burrow Authors. All rights reserved.
 * Use of this source code is governed by a BSD-style licence that can be found
 * in the LICENSE file. */

#include "internal.h"

/* clang-format off */
const burrow__HtmlEntity burrow__html_entity[] = {
EOF
	awk '{ printf "    {BURROW_S_INIT(\"%s\"), {0x%s, 0}},\n", $1, $2 }' "$tmp/one"
	cat <<'EOF'
};

const Int burrow__html_entity_len =
    (Int)(sizeof burrow__html_entity / sizeof burrow__html_entity[0]);

const burrow__HtmlEntity burrow__html_entity2[] = {
EOF
	awk '{ printf "    {BURROW_S_INIT(\"%s\"), {0x%s, 0x%s}},\n", $1, $2, $3 }' "$tmp/two"
	cat <<'EOF'
};

const Int burrow__html_entity2_len =
    (Int)(sizeof burrow__html_entity2 / sizeof burrow__html_entity2[0]);
/* clang-format on */
EOF
} > "$out.tmp"
mv "$out.tmp" "$out"
