	w("};\n\nstatic const char g_issue29437[] = %s;\nstatic const char *const g_issue29437_err = %s;\n", cq(issue29437), cerr(err))
	w("\n/* %d instants. */\n", n)
	os.Stdout.WriteString(genOut.String())
}
