#!/bin/sh
# Regenerates tests/tls_replay_client_gen.h and tests/tls_replay_server_gen.h:
# the recorded handshakes in Go's crypto/tls testdata, which the client and
# server tests replay with replayingConn. Each file is kept as an array of its
# lines, as Go's hex.Dumper wrote them, so that parseTestData reads what Go's
# reads. Go opens them by name from testdata, and the tests look them up by the
# same name in the table at the end of each header.
#
# The Go on PATH should be the release the port follows. GOROOT can be set to
# point at another source tree.
#
# Copyright 2026 The burrow Authors. All rights reserved.
# Use of this source code is governed by a BSD-style licence that can be found
# in the LICENSE file.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
goroot=${GOROOT:-$(go env GOROOT)}

python3 - "$goroot/src/crypto/tls/testdata" "$root/tests" <<'PY'
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]


def cstr(line):
    # hex.Dumper prints a dot for anything outside ' ' to '~', so a line is
    # printable ASCII. A ? is escaped so that no two of them start a trigraph.
    assert all(32 <= ord(c) < 127 for c in line), line
    return line.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?")


for side, prefix in (("client", "trc"), ("server", "trs")):
    title = side.capitalize()
    files = sorted(f for f in os.listdir(src) if f.startswith(title + "-"))
    assert files, side
    defs = []
    table = []
    seen = set()
    for name in files:
        cname = prefix + "_" + re.sub(r"[^a-z0-9]+", "_", name[len(title) + 1:].lower())
        assert cname not in seen, name
        seen.add(cname)
        with open(os.path.join(src, name)) as f:
            text = f.read()
        assert text.endswith("\n"), name
        lines = text[:-1].split("\n")
        body = "\n".join(f'    "{cstr(line)}",' for line in lines)
        defs.append(f"static const char *const {cname}[] = {{\n{body}\n    NULL,\n}};\n")
        table.append(f'    {{"{name}", {cname}}},')
    guard = f"BURROW_TESTS_TLS_REPLAY_{side.upper()}_GEN_H"
    path = os.path.join(out, f"tls_replay_{side}_gen.h")
    with open(path, "w") as f:
        f.write(f"""/* Generated by tools/gen-tls-replay-tests.sh from Go's
 * src/crypto/tls/testdata/{title}-*. Do not edit.
 *
 * Copyright 2009 The Go Authors. All rights reserved.
 * Copyright 2026 The burrow Authors. All rights reserved.
 * Use of this source code is governed by a BSD-style licence that can be found
 * in the LICENSE file. */

#ifndef {guard}
#define {guard}

#include <stddef.h>

#ifndef BURROW_TESTS_TLS_TESTDATA_FILE
#define BURROW_TESTS_TLS_TESTDATA_FILE
/* A file in testdata: its name, and its lines without their newlines, ending
 * with NULL. */
typedef struct TlsTestdataFile {{
    const char *name;
    const char *const *lines;
}} TlsTestdataFile;
#endif

""")
        f.write("\n".join(defs))
        f.write(f"\nstatic const TlsTestdataFile tls_{side}_testdata[] = {{\n")
        f.write("\n".join(table))
        f.write("\n};\n\n#endif\n")
    print(f"{path}: {len(files)} files")
PY
