#!/bin/sh
# Regenerates tests/image_color_test_gen.h: what Go's image/color makes of a
# set of colors. RGBA for every value of the one-channel colors and random
# values of the rest, every model applied to colors of every type, the
# palettes' Index and Convert for random colors, how fmt prints each type, and
# FNV-1a digests of RGBToYCbCr, YCbCrToRGB, RGBToCMYK and YCbCr.RGBA over all
# 2^24 inputs, and of CMYKToRGB and NYCbCrA.RGBA over a stride of theirs.
# Nothing depends on the machine, so this runs wherever go does.
#
