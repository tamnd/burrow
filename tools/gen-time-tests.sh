	} {
		name, off, start, end, isDST, ok := Tzset(c.s, c.end, c.sec)
		w("    {%s, %s, %s, %d, %q, %d, %s, %s, %d},\n", cq(c.s), i64(c.end), i64(c.sec), cbool(ok), name, off, i64(start), i64(end), cbool(isDST))
	}
	w("};\n\n")
	w("static const TzsetNameCase g_tzset_names[] = {\n")
	for _, s := range []string{"", "X", "PST", "PST8PDT", "PST-08", "<A+B>+08", "<A+B", "AB1", "ABCD,", "<>1"} {
		name, rest, ok := TzsetName(s)
		w("    {%s, %d, %s, %s},\n", cq(s), cbool(ok), cq(name), cq(rest))
	}
	w("};\n\n")
	w("static const TzsetOffsetCase g_tzset_offsets[] = {\n")
