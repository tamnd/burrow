#!/bin/sh
# Regenerates tests/hmac_test_gen.h: the Wycheproof vectors Go's crypto/hmac
# tests fetch as a module when they run. Go's own HMAC has to give what each
# test expects or this stops, so a vector Go would fail never gets in.
#
# Needs the network for the module, and the Go on PATH should be the release
# the port follows.
#
