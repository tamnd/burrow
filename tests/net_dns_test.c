/* Not one of Go's tests, which reach newDNSError through a Resolver. This
 * checks the flags it sets and the text, which net.go spells out. */
static void TestNewDNSErrorSetsItsFlags(TestingT *t) {
    Arena ar;
    arena_init(&ar, NULL, 0);
    Alloc *a = arena_allocator(&ar);
    static const struct {
        const char *server;
        const char *text;
        int kind; /* 0 not found, 1 temporary, 2 canceled, 3 deadline */
        bool timeout;
        bool temporary;
        bool not_found;
        bool unwraps;
    } tests[] = {
        {"", "lookup example.com: no such host", 0, false, false, true, false},
        {"8.8.8.8:53", "lookup example.com on 8.8.8.8:53: no such host", 1, false, true,
         false, false},
        {"", "lookup example.com: context canceled", 2, false, false, false, true},
        {"", "lookup example.com: context deadline exceeded", 3, true, true, false,
         true},
    };
    for (size_t i = 0; i < sizeof tests / sizeof tests[0]; i++) {
        Error cause;
        switch (tests[i].kind) {
        case 0:
            cause = burrow__net_not_found_error(a, BURROW_S("no such host"));
            break;
        case 1:
            cause = burrow__net_temporary_error(a, BURROW_S("no such host"));
            break;
        case 2:
            cause = context_canceled;
            break;
        default:
            cause = context_deadline_exceeded;
            break;
        }
        Error err = burrow__net_new_dns_error(a, cause, BURROW_S("example.com"),
                                              str_from_cstr(tests[i].server));
        const NetDNSError *de = (const NetDNSError *)errors_as(err, TYPE_NET_DNS_ERROR);
        if (de == NULL) {
            testing_t_errorf_v(t, "#%d: %v is not a DNSError", (Int)i, err);
            continue;
        }
        Str text = error_text(err);
        if (!str_eq(text, str_from_cstr(tests[i].text)))
            testing_t_errorf_v(t, "#%d: Error() = %q, want %q", (Int)i, text,
                               tests[i].text);
        if (de->is_timeout != tests[i].timeout ||
            net_dns_error_timeout(de) != tests[i].timeout)
            testing_t_errorf_v(t, "#%d: IsTimeout = %v, want %v", (Int)i,
                               de->is_timeout, tests[i].timeout);
        if (net_dns_error_temporary(de) != tests[i].temporary)
            testing_t_errorf_v(t, "#%d: Temporary() = %v, want %v", (Int)i,
                               net_dns_error_temporary(de), tests[i].temporary);
        if (de->is_not_found != tests[i].not_found)
            testing_t_errorf_v(t, "#%d: IsNotFound = %v, want %v", (Int)i,
                               de->is_not_found, tests[i].not_found);
        if (errors_is(err, cause) != tests[i].unwraps)
            testing_t_errorf_v(t, "#%d: errors.Is(err, cause) = %v, want %v", (Int)i,
                               errors_is(err, cause), tests[i].unwraps);
        if (net_error_timeout(err) != tests[i].timeout)
            testing_t_errorf_v(t, "#%d: net.Error Timeout() = %v, want %v", (Int)i,
                               net_error_timeout(err), tests[i].timeout);
    }
    arena_free(&ar);
}

