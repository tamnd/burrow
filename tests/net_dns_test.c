static void check_distribution(TestingT *t, NetSRV *data, Int n, double margin) {
    Int sum = 0;
    for (Int i = 0; i < n; i++)
        sum += data[i].weight;

    Int results[26] = {0};
    enum { COUNT = 10000 };
    NetSRV *d[26];
    for (int j = 0; j < COUNT; j++) {
        for (Int i = 0; i < n; i++)
            d[i] = &data[i];
        burrow__net_srv_shuffle_by_weight(d, n);
        results[d[0] - data]++;
    }

    Int actual = results[0];
    double expected = (double)COUNT * (double)data[0].weight / (double)sum;
    double diff = (double)actual - expected;
    testing_t_logf_v(t, "actual: %d diff: %v e: %v m: %v", actual, diff, expected,
                     margin);
    if (diff < 0)
        diff = -diff;
    if (diff > expected * margin)
        testing_t_errorf_v(t, "missed target weight: expected %v, %d", expected,
                           actual);
}

static void test_uniformity(TestingT *t, Int size, double margin) {
    static const char *const names[] = {"a", "b", "c", "d", "e",
                                        "f", "g", "h", "i", "j"};
    NetSRV data[10];
    for (Int i = 0; i < size; i++)
        data[i] = (NetSRV){.target = str_from_cstr(names[i]), .weight = 1};
    check_distribution(t, data, size, margin);
}

static void test_weighting(TestingT *t, double margin) {
    NetSRV data[] = {
        {.target = BURROW_S_INIT("a"), .weight = 60},
        {.target = BURROW_S_INIT("b"), .weight = 30},
        {.target = BURROW_S_INIT("c"), .weight = 10},
    };
    check_distribution(t, data, 3, margin);
}

static void TestDNSSRVUniformity(TestingT *t) {
    test_uniformity(t, 2, 0.05);
    test_uniformity(t, 3, 0.10);
    test_uniformity(t, 10, 0.20);
    test_weighting(t, 0.05);
}

static void TestWeighting(TestingT *t) {
    test_weighting(t, 0.05);
}

