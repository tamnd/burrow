func loadTzinfoFromZip(zipfile, name string) ([]byte, error) {
	z, err := zip.OpenReader(zipfile)
	if err != nil {
		return nil, err
	}
	defer z.Close()
	f, err := z.Open(name)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return io.ReadAll(f)
}

var genOut strings.Builder

func w(format string, args ...any) { fmt.Fprintf(&genOut, format, args...) }

// cq quotes s as a C string literal, every byte that is not plain printable
// ASCII as a three digit octal escape, which can not run into the next byte.
func cq(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\' || c == '?':
			fmt.Fprintf(&b, "\\%03o", c)
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func cerr(err error) string {
	if err == nil {
		return "NULL"
	}
	return cq(err.Error())
}

func cbool(b bool) int {
	if b {
		return 1
	}
	return 0
}

func i64(v int64) string {
	if v == math.MinInt64 {
		return "INT64_MIN"
	}
	return fmt.Sprintf("INT64_C(%d)", v)
}

func hexf(f float64) string { return strconv.FormatFloat(f, 'x', -1, 64) }

