		case i < len(zones):
			return zones[i].loc
		default:
			f := fixeds[i-len(zones)]
			return FixedZone(f.name, f.off)
		}
	}
	nloc := len(zones) + len(fixeds)

	// Instants.
	secs := []int64{
		-62135596800, -62135596801, -62135596800 + 86400*59, 0, -1, 1, 1e9, 1234567890,
		1700000000, 2159200800, -1633269601, -1633269600, 1325242799, 1325242800,
		-2e9, -5e9, 4e9, 1e11, -1e11, 253402300799, 253402300800, 951782400,
		951868800, 1104537600, 1230768000, 1293753600, 1609372800, 1711846800,
		1711850400, 1730595600, 1730599200, 1616893200, -2208988800,
		-9223372036854775808 / 2, 9223372036854775807 / 2, 20000000000,
	}
	nsecs := []int64{0, 1, 999999999, 500000000}
	w("static const TCase g_times[] = {\n")
	n := 0
	for li := -1; li < nloc; li++ {
		loc := locOf(li)
		for si, s := range secs {
			ns := nsecs[si%len(nsecs)]
			tm := Unix(s, ns).In(loc)
			y, mo, d := tm.Date()
			h, mi, sc := tm.Clock()
			iy, iw := tm.ISOWeek()
			zn, zo := tm.Zone()
			bs, be := tm.ZoneBounds()
			bin, err := tm.MarshalBinary()
			w("    {%d, %s, %d, %s, %d, %d, %d, %d, %d, %d, %d, %s, %d, %s, %d, %d, %s, %d, %s, %d, %s, %s, %s, %d, %s, %s},\n",
				li, i64(s), ns, i64(int64(y)), mo, d, h, mi, sc, tm.Weekday(), tm.YearDay(),
				i64(int64(iy)), iw, cq(zn), zo, cbool(tm.IsDST()),
				i64(bs.Unix()), cbool(bs.IsZero()), i64(be.Unix()), cbool(be.IsZero()),
				cq(string(bin)), cerr(err), i64(tm.UnixMilli()), len(bin),
				i64(tm.UnixMicro()), i64(tm.UnixNano()))
			n++
		}
	}
	w("};\n\n")

	// Date with its fields out of range, and in the gaps and overlaps.
	type dcase struct {
		y, mo, d, h, mi, s, ns int
	}
	dates := []dcase{
