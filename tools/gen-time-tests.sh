#!/bin/sh
# Regenerates tests/time_calendar_test_gen.h: what Go's package time says about
# a list of instants in a list of zones, and about the arithmetic on them.
#
# The zones are TZif files out of Go's own lib/time/zoneinfo.zip and the slim
# files in src/time/testdata, and their bytes go into the header, so the tests
# get the same answers on a machine with an old zoneinfo, or none. For every
# zone and instant it records the date, the clock, the weekday, the day of the
# year, the ISO week, the zone and its bounds and the binary encoding. Then
# Date with fields out of range, AddDate, Truncate, Round, Sub, the Duration
# methods, the tzset tables of Go's zoneinfo_test.go, and what happens to a
# TZif file cut short or with a byte flipped.
#
# The generator is a test file laid over the package with go test -overlay, so
# it can call tzset and loadTzinfoFromZip by name.
#
