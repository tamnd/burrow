#!/bin/sh
# Regenerates tests/tls_test_gen.h: the certificates and keys in Go's
# crypto/tls certificates_test.go, and parseTestCert, which is generated there
# too, read out of the Go sources so none of them is copied by hand. A few of
# the ML-DSA certificates are longer than the 4095 characters a C11 string
# literal has to hold, so each PEM is kept as an array of its lines.
#
# The Go on PATH should be the release the port follows. GOROOT can be set to
# point at another source tree.
#
# Copyright 2026 The burrow Authors. All rights reserved.
# Use of this source code is governed by a BSD-style licence that can be found
# in the LICENSE file.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/tests/tls_test_gen.h"
goroot=${GOROOT:-$(go env GOROOT)}

python3 - "$goroot/src/crypto/tls" "$out" <<'PY'
import re
import sys

src, out = sys.argv[1], sys.argv[2]

with open(f"{src}/certificates_test.go") as f:
    text = f.read()


def snake(name):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return s.lower()


defs = []
names = []


def add(cname, value):
    lines = value.split("\n")
    pieces = []
    for i, line in enumerate(lines):
        nl = "\\n" if i < len(lines) - 1 else ""
        assert len(line) <= 64 and '"' not in line and "\\" not in line, cname
        pieces.append(f'    "{line}{nl}",')
    pieces.append("    NULL,")
    names.append(cname)
    defs.append(f"static const char *const {cname}[] = {{\n" + "\n".join(pieces) + "\n};\n")


for name, value in re.findall(r"\nconst (test\w+PEM) = `(.*?)`", text, re.S):
    add(snake(name), value)
assert len(defs) == 42, len(defs)

# The PEMs TestX509KeyPair in tls_test.go declares inside itself.
with open(f"{src}/tls_test.go") as f:
    body = re.search(r"\nfunc TestX509KeyPair\(t \*testing\.T\) \{\n(.*?)\n\}\n", f.read(), re.S)
kp = re.findall(r"\n\t(?:var|const) (\w+PEM) = (?:testingKey\()?`(.*?)`",
                "\n" + body.group(1), re.S)
assert len(kp) == 6, len(kp)
for name, value in kp:
    add("x509_key_pair_" + snake(name), value)

# The certificates TestCertificateSelection in conn_test.go declares, in hex.
with open(f"{src}/conn_test.go") as f:
    body = re.search(r"\nfunc TestCertificateSelection\(t \*testing\.T\) \{\n(.*?)\n\}\n",
                     f.read(), re.S)
hx = re.findall(r"\n\tvar (cert\w+) = `([0-9a-f]+)`", "\n" + body.group(1))
assert len(hx) == 3, len(hx)
for name, value in hx:
    assert len(value) < 4095, name
    names.append(snake(name) + "_hex")
    pieces = [f'    "{value[i:i + 64]}"' for i in range(0, len(value), 64)]
    defs.append(f"static const char {snake(name)}_hex[] =\n" + "\n".join(pieces) + ";\n")
assert len(set(names)) == len(names)

with open(out, "w") as f:
    f.write(
        "/* Generated by tools/gen-tls-tests.sh from Go's crypto/tls\n"
        " * certificates_test.go, the PEMs in TestX509KeyPair in tls_test.go, which\n"
        " * are named for it here, and the hex certificates in TestCertificateSelection\n"
        " * in conn_test.go. Do not edit.\n"
        " *\n"
        " * Each PEM is its lines, NULL at the end, which tls_test_pem joins.\n"
        " *\n"
        " * Copyright 2009 The Go Authors. All rights reserved.\n"
        " * Copyright 2026 The burrow Authors. All rights reserved.\n"
        " * Use of this source code is governed by a BSD-style licence that can be found\n"
        " * in the LICENSE file. */\n\n"
        "#ifndef BURROW_TESTS_TLS_TEST_GEN_H\n#define BURROW_TESTS_TLS_TEST_GEN_H\n\n"
        '#include "burrow/burrow.h"\n'
        '#include "burrow/crypto/tls.h"\n'
        '#include "burrow/crypto/x509.h"\n'
        '#include "burrow/encoding/pem.h"\n'
        '#include "burrow/panic.h"\n\n'
        "#include <stddef.h>\n"
        "#include <string.h>\n\n"
    )
    f.write("\n".join(defs))
    f.write(
        "\n/* The lines of a PEM above joined into one []byte from a. */\n"
        "static inline Slice tls_test_pem(Alloc *a, const char *const *lines) {\n"
        "    Int n = 0;\n"
        "    for (const char *const *l = lines; *l != NULL; l++)\n"
        "        n += (Int)strlen(*l);\n"
        "    Slice b = slice_make(a, TYPE_BYTE, 0, n);\n"
        "    if (b.p == NULL)\n"
        '        panic_str(BURROW_S("tls_test_pem: out of memory"));\n'
        "    for (const char *const *l = lines; *l != NULL; l++) {\n"
        "        Int ln = (Int)strlen(*l);\n"
        "        memcpy((Byte *)b.p + b.len, *l, (size_t)ln);\n"
        "        b.len += ln;\n"
        "    }\n"
        "    return b;\n"
        "}\n\n"
        "/* parseTestCert, with the certificate and its key from a. */\n"
        "static inline TlsCertificate parse_test_cert(Alloc *a, const char *const *cert_pem,\n"
        "                                             const char *const *key_pem) {\n"
        "    TlsCertificate cert = {0};\n"
        "    Slice rest;\n"
        "    PemBlock *block = pem_decode(a, tls_test_pem(a, cert_pem), &rest);\n"
        "    if (block == NULL)\n"
        '        panic_str(BURROW_S("failed to parse certificate PEM"));\n'
        "    cert.certificate = slice_make(a, TYPE_BYTES, 1, 1);\n"
        "    if (cert.certificate.p == NULL)\n"
        '        panic_str(BURROW_S("parse_test_cert: out of memory"));\n'
        "    ((Slice *)cert.certificate.p)[0] = block->bytes;\n"
        "    cert.leaf = x509_parse_certificate(a, block->bytes, NULL);\n"
        "    if (cert.leaf == NULL)\n"
        '        panic_str(BURROW_S("failed to parse certificate"));\n'
        "    if (cert.leaf->public_key_algorithm != X509_UNKNOWN_PUBLIC_KEY_ALGORITHM) {\n"
        "        block = pem_decode(a, tls_test_pem(a, key_pem), &rest);\n"
        "        if (block == NULL)\n"
        '            panic_str(BURROW_S("failed to parse key PEM"));\n'
        "        cert.private_key = x509_parse_pkcs8_private_key(a, block->bytes, NULL);\n"
        "        if (cert.private_key.t == NULL)\n"
        '            panic_str(BURROW_S("failed to parse private key"));\n'
        "    }\n"
        "    return cert;\n"
        "}\n"
    )
    f.write("\n#endif\n")
PY
