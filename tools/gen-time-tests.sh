	}

	w("/* What Go's package time says about the cases of tools/gen-time-tests.sh,\n")
	w(" * %s. Generated by that script; do not edit. */\n\n", runtime.Version())

	w("static const TzBlob g_zones[] = {\n")
	for _, z := range zones {
