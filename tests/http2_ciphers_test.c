static void TestIsBadCipherBad(TestingT *t) {
    for (size_t i = 0; i < sizeof bad_ciphers / sizeof bad_ciphers[0]; i++) {
        uint16_t c = bad_ciphers[i];
        if (!burrow__http2_is_bad_cipher(c))
            testing_t_errorf_v(t, "Wrong result for isBadCipher(%d), want true", c);
    }
}

