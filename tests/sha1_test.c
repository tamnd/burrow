static Int sum(Slice in, Byte *out) {
    Sha1SumRet r = sha1_sum(in);
    memcpy(out, r.a, sizeof r.a);
    return (Int)sizeof r.a;
}

static void TestGolden(TestingT *t) {
    testdigest_golden(t, "sha1", sum, sha1_new, golden, NGOLD(golden));
}

static void TestSize(TestingT *t) {
    testdigest_sizes(t, "New", sha1_new, SHA1_SIZE, SHA1_BLOCK_SIZE);
}

static void TestGoldenMarshal(TestingT *t) {
    testdigest_golden_marshal(t, "sha1", true, sha1_new, golden, NGOLD(golden));
}

static void TestBlockSize(TestingT *t) {
    Arena ar;
    arena_init(&ar, NULL, 0);
    Hash c = sha1_new(arena_allocator(&ar));
    Int got = hash_block_size(c);
    if (got != SHA1_BLOCK_SIZE)
        testing_t_errorf_v(t, "BlockSize = %d; want %d", got, (Int)SHA1_BLOCK_SIZE);
    arena_free(&ar);
}

static void TestLargeHashes(TestingT *t) {
    testdigest_large_hashes(t, sha1_new, large_unmarshal_tests,
                            NGOLD(large_unmarshal_tests));
}

