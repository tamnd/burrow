#!/bin/sh
# Regenerates tests/go_types_check_test_gen.h for the go/types check tests. It
# holds what check_test.go reads from disk: every file under
# src/internal/types/testdata/{check,spec,examples,fixedbugs} and
# src/go/types/testdata/local, in the order os.ReadDir gives them, with each
# directory kept together as one package.
#
# A file can be bigger than the 64K MSVC takes in one string literal, so each
# one goes out as a list of pieces to put back together.
#
# GOROOT says which Go to read, and defaults to what go env says.
#
# Copyright 2026 The burrow Authors. All rights reserved.
# Use of this source code is governed by a BSD-style licence that can be found
# in the LICENSE file.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
goroot=${GOROOT:-$(go env GOROOT)}
out="$root/tests/go_types_check_test_gen.h"

python3 - "$goroot" > "$out" <<'PY'
import os
import re
import sys

goroot = sys.argv[1]
gover = open(os.path.join(goroot, "VERSION")).readline().strip()

# Bytes of a file to each piece, well under what MSVC takes once escaped.
CHUNK = 12000

# The libc calls tools/check-banned.sh looks for. The first letter of a name
# like that goes out as an octal escape so the check does not take the text
# for a call.
BANNED = re.compile(
    rb"(?<![A-Za-z0-9_])(strcpy|strcat|sprintf|vsprintf|gets|strtok|strncpy|"
    rb"strncat|alloca|atoi|atol|atof)[ \t]*\("
)

# And the allocator names tools/check-banned.sh wants kept in the malloc
# backend, which it looks for as words, called or not.
BANNED_ALLOC = re.compile(
    rb"(?<![A-Za-z0-9_])(malloc|calloc|realloc|free|aligned_alloc|posix_memalign|"
    rb"_aligned_malloc|_aligned_realloc|_aligned_free)(?![A-Za-z0-9_])"
)


def lit(b):
    """b as C string literals, one line of the text to each."""
    lines, cur = [], ""
    hide = {m.start() for m in BANNED.finditer(b)}
    hide |= {m.start() for m in BANNED_ALLOC.finditer(b)}
    for i, c in enumerate(b):
        if i in hide:
            s = "\\%03o" % c
        elif c == 10:
            s = "\\n"
        elif c == 9:
            s = "\\t"
        elif c == 34:
            s = '\\"'
        elif c == 92:
            s = "\\\\"
        elif c == 63 and i + 1 < len(b) and b[i + 1] == 63:
            s = "\\?"
        elif 32 <= c < 127:
            s = chr(c)
        else:
            s = "\\%03o" % c
        # an octal escape must not run into a digit after it
        if s.startswith("\\") and s[1:].isdigit() and i + 1 < len(b):
            nxt = b[i + 1]
            if 48 <= nxt <= 55:
                cur += s
                lines.append('"' + cur + '"')
                cur = ""
                continue
        cur += s
        if c == 10 or len(cur) >= 70:
            lines.append('"' + cur + '"')
            cur = ""
    if cur or not lines:
        lines.append('"' + cur + '"')
    return lines


def pieces(b):
    out = []
    for i in range(0, max(len(b), 1), CHUNK):
        out.append(b[i : i + CHUNK])
    return out


SUITES = [
    ("check", os.path.join(goroot, "src", "internal", "types", "testdata", "check")),
    ("spec", os.path.join(goroot, "src", "internal", "types", "testdata", "spec")),
    ("examples", os.path.join(goroot, "src", "internal", "types", "testdata", "examples")),
    ("fixedbugs", os.path.join(goroot, "src", "internal", "types", "testdata", "fixedbugs")),
    ("local", os.path.join(goroot, "src", "go", "types", "testdata", "local")),
]

# (suite, package name, [(file name, path)]): a file on its own, or a
# directory whose files make up one package, as testDirFiles has them.
pkgs = []
for suite, d in SUITES:
    for fi in sorted(os.listdir(d)):
        path = os.path.join(d, fi)
        if os.path.isdir(path):
            fs = [("testdata/%s/%s/%s" % (suite, fi, f), os.path.join(path, f))
                  for f in sorted(os.listdir(path))]
            pkgs.append((suite, fi, fs))
        else:
            pkgs.append((suite, fi, [("testdata/%s/%s" % (suite, fi), path)]))

w = sys.stdout.write
w("/* What Go's go/types check tests read, from src/internal/types/testdata and\n")
w(" * src/go/types/testdata of %s.\n" % gover)
w(" * Generated by tools/gen-go-types-tests.sh; do not edit. */\n\n")
w("typedef struct GtckPiece {\n    const char *p;\n    long long n;\n} GtckPiece;\n\n")
w("#define GTCK_P(x) {x, (long long)sizeof(x) - 1}\n\n")
w("typedef struct GtckFile {\n    const char *name;\n    const GtckPiece *pieces;\n")
w("    int npieces;\n} GtckFile;\n\n")
w("/* One package: suite is the test that reads it, name the file or directory\n")
w(" * name, and its files are gtck_files[first] on, nfiles of them. */\n")
w("typedef struct GtckPkg {\n    const char *suite, *name;\n    int first, nfiles;\n")
w("} GtckPkg;\n\n")

k = 0
for _, _, fs in pkgs:
    for name, path in fs:
        data = open(path, "rb").read()
        w("static const GtckPiece gtck_file_%d[] = {\n" % k)
        for p in pieces(data):
            w("    GTCK_P(" + "\n           ".join(lit(p)) + "),\n")
        w("};\n\n")
        k += 1

w("static const GtckFile gtck_files[] = {\n")
k = 0
for _, _, fs in pkgs:
    for name, _ in fs:
        w('    {"%s", gtck_file_%d, (int)(sizeof(gtck_file_%d) / sizeof(gtck_file_%d[0]))},\n'
          % (name, k, k, k))
        k += 1
w("};\n\n")

w("static const GtckPkg gtck_pkgs[] = {\n")
k = 0
for suite, name, fs in pkgs:
    w('    {"%s", "%s", %d, %d},\n' % (suite, name, k, len(fs)))
    k += len(fs)
w("};\n")
PY

if command -v clang-format >/dev/null 2>&1; then
	clang-format -i "$out"
fi
