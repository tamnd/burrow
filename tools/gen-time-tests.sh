			}
		}
	}
	w("};\n\n")

	// Truncate and Round, which work from the zero time and ignore the
	// location.
	durs := []Duration{0, -1, 1, 2, 3, 7, Microsecond, Millisecond, Second, 2 * Second, Minute, 10 * Minute, Hour, 3 * Hour, 24 * Hour, 7 * 24 * Hour, 1<<62 + 3, 1<<63 - 1, 17 * Second / 3, 1e18}
	tsecs := []int64{0, 1, -1, 1e9, -62135596800, 1700000000, -1e11, 1e11, 253402300799}
