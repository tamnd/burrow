#!/bin/sh
# Regenerates tests/bzip2_test_gen.h: a set of bzip2 streams, Go's own test
# files and some made with bzip2(1), with what Go's compress/bzip2 reader makes
# of each of them, and of each of the small ones with single bits flipped, cut
# short and with bytes after the end. tests/bzip2_test.c reads every stream the
# same way and has to get the same bytes and the same error. bzip2(1) is only
# needed here, to make the streams, which are then part of the header.
#
