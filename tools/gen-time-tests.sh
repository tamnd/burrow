		w("    {%s, %q},\n", i64(int64(d)), Weekday(d).String())
	}
	w("};\n\n")

	// UnmarshalBinary on bad input.
	w("static const BinCase g_bins[] = {\n")
	for _, b := range []string{"", "\x00", "\x01", "\x02", "\x03", "\x01\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\xff",
		"\x01\x00\x00\x00\x0e\x77\x91\xf7\x00\x00\x00\x00\x00\xff\xff",
		"\x01\x00\x00\x00\x0e\x77\x91\xf7\x00\x00\x00\x00\x00\xff\xff\x00",
		"\x02\x00\x00\x00\x0e\x77\x91\xf7\x00\x00\x00\x00\x00\x00\x3c\x00",
		"\x02\x00\x00\x00\x0e\x77\x91\xf7\x00\x00\x00\x00\x00\x00\x3c\x00\x2d",
		"\x01\x00\x00\x00\x0e\x77\x91\xf7\x00\x00\x00\x00\x00\x00\x3c",
		"\x01\x00\x00\x00\x0e\x77\x91\xf7\x00\x3b\x9a\xc9\xff\x02\x1c"} {
		var tm Time
		err := tm.UnmarshalBinary([]byte(b))
		zn, zo := tm.Zone()
		w("    {%s, %d, %s, %s, %d, %s, %d},\n", cq(b), len(b), cerr(err), i64(tm.Unix()), tm.Nanosecond(), cq(zn), zo)
	}
	w("};\n\n")

	// tzset and its pieces, Go's tables and a few more.
	w("static const TzsetCase g_tzset[] = {\n")
	for _, c := range []struct {
		s        string
		end, sec int64
	}{
		{"", 0, 0}, {"PST8PDT,M3.2.0,M11.1.0", 0, 2159200800}, {"PST8PDT,M3.2.0,M11.1.0", 0, 2152173599},
		{"PST8PDT,M3.2.0,M11.1.0", 0, 2152173600}, {"PST8PDT,M3.2.0,M11.1.0", 0, 2152173601},
		{"PST8PDT,M3.2.0,M11.1.0", 0, 2172733199}, {"PST8PDT,M3.2.0,M11.1.0", 0, 2172733200},
