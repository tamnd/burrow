set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/tests/cipher_test_gen.h"
goroot=$(go env GOROOT)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# The version Go's tests pin, from cryptotest/wycheproof/schemaversion.go.
wycheproof_version=$(sed -n 's/^const wycheproofVersion = "\(.*\)"$/\1/p' \
	"$goroot/src/crypto/internal/cryptotest/wycheproof/schemaversion.go")
wycheproof_dir=$( (cd "$tmp" && go mod download -json "github.com/c2sp/wycheproof@$wycheproof_version") |
	sed -n 's/^[[:space:]]*"Dir": "\(.*\)",$/\1/p')

mkdir "$tmp/gen"
cat >"$tmp/gen/main.go" <<'GO'
package main

import (
	"crypto/aes"
	"crypto/cipher"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"
)

// C string literal of s, with octal escapes so nothing runs into the next
// character. A C99 compiler only has to take 4095 characters in one.
func lit(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '?':
			b.WriteString(`\077`)
		case c >= ' ' && c <= '~':
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	if b.Len() > 4095+2 {
		log.Fatalf("literal of %d characters is too long", b.Len()-2)
	}
	return b.String()
}

func unhex(s string) []byte {
	b, err := hex.DecodeString(s)
	if err != nil {
		log.Fatalf("invalid hex %q: %v", s, err)
	}
	return b
}

func main() {
	wycheproofDir := os.Args[1]

	file := "aes_cbc_pkcs5_test.json"
	data, err := os.ReadFile(filepath.Join(wycheproofDir, file))
	if err != nil {
		log.Fatal(err)
	}
	var wp struct {
		TestGroups []struct {
			Tests []struct {
				TcId    int      `json:"tcId"`
				Comment string   `json:"comment"`
				Key     string   `json:"key"`
				Iv      string   `json:"iv"`
				Msg     string   `json:"msg"`
				Ct      string   `json:"ct"`
				Result  string   `json:"result"`
				Flags   []string `json:"flags"`
			} `json:"tests"`
		} `json:"testGroups"`
	}
	if err := json.Unmarshal(data, &wp); err != nil {
		log.Fatal(err)
	}
	var tests strings.Builder
	for _, tg := range wp.TestGroups {
		for _, tv := range tg.Tests {
			fail := func(format string, args ...any) {
				log.Fatalf("%s #%d: Go's CBC: %s", file, tv.TcId, fmt.Sprintf(format, args...))
			}
			block, err := aes.NewCipher(unhex(tv.Key))
			if err != nil {
				fail("NewCipher: %v", err)
			}
			mode := cipher.NewCBCDecrypter(block, unhex(tv.Iv))
			ct := unhex(tv.Ct)
			if len(ct)%aes.BlockSize != 0 {
				fail("ciphertext is not a multiple of the block size")
			}
			mode.CryptBlocks(ct, ct)
			badPadding := false
			for _, flag := range tv.Flags {
				if flag == "BadPadding" || flag == "NoPadding" {
					badPadding = true
				}
			}
			if !badPadding {
				// wycheproof.ShouldPass with no flags that pass.
				switch tv.Result {
				case "valid":
				case "acceptable":
					for _, f := range tv.Flags {
						log.Fatalf("%s #%d: unspecified flag: %q", file, tv.TcId, f)
					}
				case "invalid":
					fail("unexpected invalid test (not BadPadding/NoPadding)")
				default:
					log.Fatalf("%s #%d: unexpected result %q", file, tv.TcId, tv.Result)
				}
				padding := ct[len(ct)-1]
				paddingNum := int(padding)
				for i := paddingNum; i > 0; i-- {
					if ct[len(ct)-i] != padding {
						fail("bad padding at index=%d of %v", i, ct)
					}
				}
				ct = ct[:len(ct)-paddingNum]
				if got, want := hex.EncodeToString(ct), tv.Msg; got != want {
					fail("decoded ciphertext not equal: %s, want %s", got, want)
				}
			}
			fmt.Fprintf(&tests, "    {%s, %d, %s, %s, %s, %s, %s, %v},\n", lit(file), tv.TcId,
				lit(tv.Comment), lit(tv.Key), lit(tv.Iv), lit(tv.Msg), lit(tv.Ct), badPadding)
		}
	}
	fmt.Println("/* The Wycheproof tests: the file, the tcId, the comment, the key, the IV,")
	fmt.Println(" * the message and the ciphertext in hex, and whether the flags say")
	fmt.Println(" * BadPadding or NoPadding. The rest are all valid. */")
	fmt.Println("static const GenWycheproof gen_wycheproof[] = {")
	fmt.Print(tests.String())
	fmt.Println("};")
}
GO

{
	cat <<EOF
/* Generated by tools/gen-cipher-tests.sh; do not edit.
 *
 * The Wycheproof vectors Go's crypto/cipher CBC test reads, from $(go env GOVERSION)
 * and github.com/c2sp/wycheproof at $wycheproof_version. */

#ifndef BURROW_TESTS_CIPHER_TEST_GEN_H
#define BURROW_TESTS_CIPHER_TEST_GEN_H

#include <stdbool.h>

typedef struct {
    const char *file;
    int tc_id;
    const char *comment;
    const char *key, *iv, *msg, *ct;
    bool bad_padding;
} GenWycheproof;

EOF
	(cd "$tmp/gen" && GO111MODULE=off go run main.go "$wycheproof_dir/testvectors_v1")
	cat <<'EOF'

#endif /* BURROW_TESTS_CIPHER_TEST_GEN_H */
EOF
} >"$tmp/out.h"
mv "$tmp/out.h" "$out"
