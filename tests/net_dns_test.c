/* The want's search, or dnsDefaultSearch when it has none, as Go's test
 * does. */
static Slice want_search(Alloc *a, const DNSConfigWant *w) {
    if (w->nsearch == 0)
        return burrow__dns_default_search(a, fake_hostname);
    return cstrs(a, w->search, w->nsearch);
}

/* reflect.DeepEqual on the two, with mtime cleared as Go clears it. */
static bool config_eq(Alloc *a, const burrow__DNSConfig *c, const DNSConfigWant *w) {
    Slice servers = w->nservers < 0
                        ? cstrs(a, (const char *const[]){"127.0.0.1:53", "[::1]:53"}, 2)
                        : cstrs(a, w->servers, w->nservers);
    return strs_eq(c->servers, servers) && strs_eq(c->search, want_search(a, w)) &&
           c->ndots == w->ndots && c->timeout == w->timeout &&
           c->attempts == w->attempts && c->rotate == w->rotate &&
           c->unknown_opt == w->unknown_opt &&
           strs_eq(c->lookup, cstrs(a, w->lookup, w->nlookup)) && BURROW_OK(c->err) &&
           c->soffset == 0 && c->single_request == w->single_request &&
           c->use_tcp == w->use_tcp && !c->trust_ad && !c->no_reload;
}

static Str config_string(Alloc *a, const burrow__DNSConfig *c) {
    return fmt_sprintf_v(a,
                         "{servers:%s search:%s ndots:%d timeout:%d attempts:%d "
                         "rotate:%v unknownOpt:%v lookup:%s err:%v singleRequest:%v "
                         "useTCP:%v trustAD:%v noReload:%v}",
                         strs(a, c->servers), strs(a, c->search), c->ndots,
                         (Int)c->timeout, c->attempts, c->rotate, c->unknown_opt,
                         strs(a, c->lookup), c->err, c->single_request, c->use_tcp,
                         c->trust_ad, c->no_reload);
}

