static void test_static_host(TestingT *t, Alloc *a, const char *hosts_path,
                             const StaticHostEntry *ent) {
    Str in0 = str_from_cstr(ent->in);
    Str ins[4] = {in0, abs_name(a, in0), strings_to_lower(a, in0),
                  strings_to_upper(a, in0)};
    Slice want = cstrs(a, ent->out, ent->nout);
    for (int i = 0; i < 4; i++) {
        Str canonical;
        Slice addrs = burrow__net_lookup_static_host(a, ins[i], &canonical);
        if (!strs_eq(addrs, want))
            testing_t_errorf_v(t, "%s, lookupStaticHost(%s) = %s; want %s", hosts_path,
                               ins[i], strs(a, addrs), strs(a, want));
    }
}

