#!/bin/sh
# Regenerates tests/lzw_test_gen.h: what Go's compress/lzw writer makes of a
# set of inputs in both bit orders at every literal width the input fits in,
# for tests/lzw_test.c to match byte for byte, and what Go's reader makes of
# random bytes and of cut short streams, for the reader to match. Nothing in Go's lzw depends on
# the machine, so this runs wherever go does.
#
