/* Go's longDomain: five labels of 63 a's and then "example". */
static Str long_domain(Alloc *a) {
    Str char63 = strings_repeat(a, BURROW_S("a"), 63);
    Str label =
        strings_join(a, slice_from((Str[]){char63, BURROW_S(".")}, 2, 2, TYPE_STRING),
                     BURROW_STR_EMPTY);
    return strings_join(
        a,
        slice_from((Str[]){strings_repeat(a, label, 5), BURROW_S("example")}, 2, 2,
                   TYPE_STRING),
        BURROW_STR_EMPTY);
}

static Str cat2(Alloc *a, Str x, Str y) {
    return strings_join(a, slice_from((Str[]){x, y}, 2, 2, TYPE_STRING),
                        BURROW_STR_EMPTY);
}

static void TestDNSNameLength(TestingT *t) {
    Arena ar;
    arena_init(&ar, NULL, 0);
    Alloc *a = arena_allocator(&ar);
    Str dir = write_testdata(t, a);
    if (dir.len == 0) {
        arena_free(&ar);
        return;
    }
    fake_hostname_name = "host.domain.local";
    fake_hostname_fails = false;
    Str ld = long_domain(a);
    for (size_t k = 0;
         k < sizeof dns_read_config_tests / sizeof dns_read_config_tests[0]; k++) {
        const char *name = dns_read_config_tests[k].name;
        burrow__DNSConfig conf;
        burrow__dns_read_config(a, td(a, dir, name), fake_hostname, &conf);
        if (BURROW_FAILED(conf.err)) {
            testing_t_fatal_v(t, conf.err);
            break;
        }
        Slice suffixes = want_search(a, &dns_read_config_tests[k].want);
        Int shortest = 0;
        for (Int i = 0; i < suffixes.len; i++) {
            Int n = ((const Str *)suffixes.p)[i].len;
            if (shortest == 0 || n < shortest)
                shortest = n;
        }

        /* A name that will be maximally long when prefixing the shortest
         * suffix, counting the dot between. */
        Int from = ld.len - 254 + 1 + shortest;
        Str long_name = str_from_bytes(ld.p + from, ld.len - from);
        if (long_name.p[0] == '.' || long_name.p[1] == '.')
            long_name = cat2(a, BURROW_S("aa."),
                             str_from_bytes(long_name.p + 3, long_name.len - 3));
        Slice fqdns = burrow__dns_config_name_list(&conf, a, long_name);
        for (Int i = 0; i < fqdns.len; i++) {
            Int n = ((const Str *)fqdns.p)[i].len;
            if (n > 254)
                testing_t_errorf_v(t, "got %d; want less than or equal to 254", n);
        }

        /* Now a name that's too long for suffixing. */
        Str unsuffixable =
            cat2(a, BURROW_S("a."), str_from_bytes(long_name.p + 1, long_name.len - 1));
        Slice res = burrow__dns_config_name_list(&conf, a, unsuffixable);
        if (res.len != 1)
            testing_t_errorf_v(t, "suffixed names %s; want []", strs(a, res));

        /* And a name that's too long for DNS. */
        Str too_long = cat2(a, BURROW_S("a."), ld);
        res = burrow__dns_config_name_list(&conf, a, too_long);
        if (res.p != NULL)
            testing_t_errorf_v(t, "suffixed names %s; want nil", strs(a, res));
    }
    (void)os_remove_all(dir);
    arena_free(&ar);
}

