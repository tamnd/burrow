#!/bin/sh
# Regenerates src/index/suffixarray_sais2.h from src/index/suffixarray_sais.h.
#
# This is Go's src/index/suffixarray/gen.go, which makes sais2.go from sais.go
# by copying functions with the types changed. It reads the same way: a
# function whose name ends in _32 is copied with 32 changed to 64, and one
# whose name ends in _8_32 is also copied with the byte text widened to int32,
# once as it is and once more with 32 changed to 64. The widened copies drop
# every line that has "256" or "byte-only" in it.
#
# Three things are not in gen.go. The replacements that widen the text have
# two more pairs, SaisBytes to SaisInt32s and Byte to int32_t, since that is
# how C spells the types. A function here starts at a line that begins with
# "static" and has its "{" before any ";", which leaves out the prototypes.
# And the copies call each other before they are defined, so the output starts
# with a prototype for each one that suffixarray_sais.h has not declared
# already.
#
# The output is formatted with clang-format, or with $CLANG_FORMAT, which
# should be the release CI pins.
#
# Copyright 2026 The burrow Authors. All rights reserved.
# Use of this source code is governed by a BSD-style licence that can be found
# in the LICENSE file.
set -eu
cd "$(dirname "$0")/.."
exec python3 - <<'PY'
import os
import re
import shutil
import subprocess
import sys


def fail(msg):
    sys.exit("gen-suffixarray: " + msg)


def replacer(*pairs):
    # strings.NewReplacer: the leftmost match wins, and of the olds that match
    # at the same place, the first one given.
    olds = pairs[0::2]
    news = pairs[1::2]

    def replace(s):
        out = []
        i = 0
        while i < len(s):
            for old, new in zip(olds, news):
                if s.startswith(old, i):
                    out.append(new)
                    i += len(old)
                    break
            else:
                out.append(s[i])
                i += 1
        return "".join(out)

    return replace


fix32 = replacer("32", "64", "int32", "int64")
fix8_32 = replacer("_8_32", "_32", "byte", "int32", "SaisBytes", "SaisInt32s", "Byte", "int32_t")


def strip_byte_only(s):
    lines = s.splitlines(keepends=True)
    return "".join(l for l in lines if "256" not in l and "byte-only" not in l)


src = "src/index/suffixarray_sais.h"
dst = "src/index/suffixarray_sais2.h"
with open(src, encoding="utf-8") as f:
    data = f.read()

x = data.find("\n\n")
if x < 0:
    fail("cannot find blank line after copyright comment")
head = data[:x]

# The names suffixarray_sais.h declares without defining.
declared = set()
for m in re.finditer(r"\nstatic [^;{]*?(\w+)\([^;{]*\);", data):
    declared.add(m.group(1))

fns = []
rest = data
while True:
    x = rest.find("\nstatic ")
    if x < 0:
        break
    rest = rest[x:]
    brace = rest.find("{")
    semi = rest.find(";")
    if brace < 0 or (0 <= semi < brace):
        rest = rest[len("\nstatic "):]
        continue
    p = rest.find("(")
    name = re.search(r"(\w+)$", rest[:p]).group(1)
    x = rest.find("\n}\n")
    if x < 0:
        fail("cannot find end of func %s" % name)
    fn = rest[: x + len("\n}\n")]
    rest = rest[x + len("\n}") :]

    if name.endswith("_32"):
        fns.append(fix32(fn))
    if name.endswith("_8_32"):
        # x_8_32 -> x_8_64 done above
        fn = fix8_32(strip_byte_only(fn))
        fns.append(fn)
        fns.append(fix32(fn))

protos = []
for fn in fns:
    sig = fn[1 : fn.index("{")].rstrip()
    name = re.search(r"(\w+)\(", sig).group(1)
    if name not in declared:
        protos.append(sig + ";\n")

out = head + "\n\n/* Code generated by tools/gen-suffixarray.sh; DO NOT EDIT. */\n\n"
out += "".join(protos)
out += "".join(fns)
with open(dst, "w", encoding="utf-8") as f:
    f.write(out)

fmt = os.environ.get("CLANG_FORMAT", "clang-format")
if shutil.which(fmt) is None:
    fail("no %s; set CLANG_FORMAT to the one CI uses" % fmt)
subprocess.run([fmt, "-i", dst], check=True)
PY
