# Regenerates tests/quotedprintable_test_gen.h: what Go's mime/quotedprintable
# reader makes of Go's own test inputs and of more, read all at once and one
# byte at a time, a digest of what it makes of every string of up to six bytes
# from "0A \r\n=\t", and what the writer makes of Go's inputs and of random
# ones, written whole and in pieces, as text and as binary. Nothing in the
# package depends on the machine, so this runs wherever go does.
