# in the LICENSE file.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/tests/pbkdf2_test_gen.h"
goroot=$(go env GOROOT)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# The version Go's tests pin, from cryptotest/wycheproof/schemaversion.go.
wycheproof_version=$(sed -n 's/^const wycheproofVersion = "\(.*\)"$/\1/p' \
	"$goroot/src/crypto/internal/cryptotest/wycheproof/schemaversion.go")
wycheproof_dir=$( (cd "$tmp" && go mod download -json "github.com/c2sp/wycheproof@$wycheproof_version") |
	sed -n 's/^[[:space:]]*"Dir": "\(.*\)",$/\1/p')

mkdir "$tmp/gen"
cat >"$tmp/gen/main.go" <<'GO'
package main

import (
	"bytes"
	"crypto/pbkdf2"
	"crypto/sha1"
	"crypto/sha256"
	"crypto/sha512"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"hash"
	"log"
	"os"
	"path/filepath"
	"strings"
)

// C string literal of s, with octal escapes so nothing runs into the next
// character. A C99 compiler only has to take 4095 characters in one.
func lit(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '?':
			b.WriteString(`\077`)
		case c >= ' ' && c <= '~':
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	if b.Len() > 4095+2 {
		log.Fatalf("literal of %d characters is too long", b.Len()-2)
	}
	return b.String()
}

func unhex(s string) []byte {
	b, err := hex.DecodeString(s)
	if err != nil {
		log.Fatalf("invalid hex %q: %v", s, err)
	}
	return b
}

// The files TestWycheproof reads, in the order of its map.
var files = []struct {
	name string
	h    func() hash.Hash
}{
	{"pbkdf2_hmacsha1_test.json", sha1.New},
	{"pbkdf2_hmacsha224_test.json", sha256.New224},
	{"pbkdf2_hmacsha256_test.json", sha256.New},
	{"pbkdf2_hmacsha384_test.json", sha512.New384},
	{"pbkdf2_hmacsha512_test.json", sha512.New},
}

func main() {
	wycheproofDir := os.Args[1]

	var tests strings.Builder
	for _, file := range files {
		data, err := os.ReadFile(filepath.Join(wycheproofDir, file.name))
		if err != nil {
			log.Fatal(err)
		}
		var wp struct {
			TestGroups []struct {
				Tests []struct {
					TcId           int      `json:"tcId"`
					Comment        string   `json:"comment"`
					Password       string   `json:"password"`
					Salt           string   `json:"salt"`
					IterationCount int      `json:"iterationCount"`
					DkLen          int      `json:"dkLen"`
					Dk             string   `json:"dk"`
					Result         string   `json:"result"`
					Flags          []string `json:"flags"`
				} `json:"tests"`
			} `json:"testGroups"`
		}
		if err := json.Unmarshal(data, &wp); err != nil {
			log.Fatal(err)
		}
		for _, tg := range wp.TestGroups {
			for _, tv := range tg.Tests {
				// wycheproof.ShouldPass with no flags that pass.
				var wantPass bool
				switch tv.Result {
				case "valid":
					wantPass = true
				case "invalid":
					wantPass = false
				case "acceptable":
					wantPass = true
					for _, f := range tv.Flags {
						log.Fatalf("%s #%d: unspecified flag: %q", file.name, tv.TcId, f)
					}
				default:
					log.Fatalf("%s #%d: unexpected result %q", file.name, tv.TcId, tv.Result)
				}
				dk, err := pbkdf2.Key(file.h, string(unhex(tv.Password)), unhex(tv.Salt), tv.IterationCount, tv.DkLen)
				switch {
				case err != nil && wantPass:
					log.Fatalf("%s #%d: Go's Key: %v", file.name, tv.TcId, err)
				case err == nil && !wantPass:
					log.Fatalf("%s #%d: Go's Key unexpectedly succeeded", file.name, tv.TcId)
				case err == nil && !bytes.Equal(dk, unhex(tv.Dk)):
					log.Fatalf("%s #%d: Go's Key gives %x, want %s", file.name, tv.TcId, dk, tv.Dk)
				}
				fmt.Fprintf(&tests, "    {%s, %d, %s, %s, %s, %d, %d, %s, %v},\n", lit(file.name),
					tv.TcId, lit(tv.Comment), lit(tv.Password), lit(tv.Salt), tv.IterationCount,
					tv.DkLen, lit(tv.Dk), wantPass)
			}
		}
	}
	fmt.Println("/* The Wycheproof tests: the file, the tcId, the comment, the password and")
	fmt.Println(" * the salt in hex, the iteration count, the key length, the derived key in")
	fmt.Println(" * hex, and whether the test is valid. */")
	fmt.Println("static const GenWycheproof gen_wycheproof[] = {")
	fmt.Print(tests.String())
	fmt.Println("};")
}
GO

{
	cat <<EOF
/* Generated by tools/gen-pbkdf2-tests.sh; do not edit.
 *
 * The Wycheproof vectors Go's crypto/pbkdf2 tests read, from $(go env GOVERSION)
 * and github.com/c2sp/wycheproof at $wycheproof_version. */

#ifndef BURROW_TESTS_PBKDF2_TEST_GEN_H
#define BURROW_TESTS_PBKDF2_TEST_GEN_H

#include <stdbool.h>

typedef struct {
    const char *file;
    int tc_id;
    const char *comment;
    const char *password, *salt;
    int iteration_count, dk_len;
    const char *dk;
    bool want_pass;
} GenWycheproof;

EOF
	(cd "$tmp/gen" && GO111MODULE=off go run main.go "$wycheproof_dir/testvectors_v1")
	cat <<'EOF'

#endif /* BURROW_TESTS_PBKDF2_TEST_GEN_H */
EOF
} >"$tmp/out.h"
mv "$tmp/out.h" "$out"
