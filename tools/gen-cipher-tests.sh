# Regenerates tests/cipher_test_gen.h: the Wycheproof vectors Go's CBC test
# in crypto/cipher fetches as a module when it runs. Go's own AES-CBC has to do
# what the test expects of each one or this stops, so a vector Go would fail
# never gets in.
#
# Needs the network for the module, and the Go on PATH should be the release
# the port follows.
#
