static void TestReadLine(TestingT *t) {
#if defined(BURROW_OS_WINDOWS) || defined(BURROW_OS_WASI)
    testing_t_skip_v(t, "no /etc/services here");
    return;
#else
    Arena ar;
    arena_init(&ar, NULL, 0);
    Alloc *a = arena_allocator(&ar);
    Str filename = BURROW_S("/etc/services"); /* a nice big file */
    Error err = BURROW_NO_ERROR;
    Slice whole = os_read_file(a, filename, &err);
    if (BURROW_FAILED(err)) {
        arena_free(&ar);
        testing_t_skipf_v(t, "skipping because failed to open /etc/services: %v", err);
        return;
    }
    burrow__NetFile *file = burrow__net_open(a, filename, &err);
    if (file == NULL) {
        arena_free(&ar);
        testing_t_fatal_v(t, err);
        return;
    }
    const Byte *p = (const Byte *)whole.p;
    Int pos = 0;
    Int lineno = 1;
    Int byteno = 0;
    for (;;) {
        /* bufio's ReadString('\n') over the same bytes. */
        Str bline = BURROW_STR_EMPTY;
        bool berr = false;
        const Byte *nl =
            pos < whole.len
                ? (const Byte *)memchr(p + pos, '\n', (size_t)(whole.len - pos))
                : NULL;
        if (nl != NULL) {
            bline = str_from_bytes(p + pos, (Int)(nl - (p + pos)) + 1);
            pos += bline.len;
        } else {
            bline = str_from_bytes(p + pos, whole.len - pos);
            pos = whole.len;
            berr = true;
        }
        if (bline.len > 0)
            bline.len--;
        Str line;
        bool ok = burrow__net_file_read_line(file, &line);
        if (berr != !ok || !str_eq(bline, line)) {
            testing_t_fatalf_v(t, "%s:%d (#%d)\nbufio => %q, %v\nnet => %q, %v",
                               filename, lineno, byteno, bline, berr, line, ok);
            break;
        }
        if (!ok)
            break;
        lineno++;
        byteno += line.len + 1;
    }
    burrow__net_file_close(file, a);
    arena_free(&ar);
#endif
}

static void TestDtoi(TestingT *t) {
    static const struct {
        const char *in;
        Int out;
        Int off;
        bool ok;
    } tests[] = {
        {"", 0, 0, false},         {"0", 0, 1, true},
        {"65536", 65536, 5, true}, {"123456789", BURROW__NET_BIG, 8, false},
        {"-0", 0, 0, false},       {"-1234", 0, 0, false},
    };
    for (size_t k = 0; k < sizeof tests / sizeof tests[0]; k++) {
        Int n = -1;
        Int i = -1;
        bool ok = burrow__net_dtoi(str_from_cstr(tests[k].in), &n, &i);
        if (n != tests[k].out || i != tests[k].off || ok != tests[k].ok)
            testing_t_errorf_v(t, "got %d, %d, %v; want %d, %d, %v", n, i, ok,
                               tests[k].out, tests[k].off, tests[k].ok);
    }
}

