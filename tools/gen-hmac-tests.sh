# in the LICENSE file.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/tests/hmac_test_gen.h"
goroot=$(go env GOROOT)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# The version Go's tests pin, from cryptotest/wycheproof/schemaversion.go.
wycheproof_version=$(sed -n 's/^const wycheproofVersion = "\(.*\)"$/\1/p' \
	"$goroot/src/crypto/internal/cryptotest/wycheproof/schemaversion.go")
wycheproof_dir=$( (cd "$tmp" && go mod download -json "github.com/c2sp/wycheproof@$wycheproof_version") |
	sed -n 's/^[[:space:]]*"Dir": "\(.*\)",$/\1/p')

mkdir "$tmp/gen"
cat >"$tmp/gen/main.go" <<'GO'
package main

import (
	"bytes"
	"crypto/hmac"
	"crypto/sha1"
	"crypto/sha256"
	"crypto/sha3"
	"crypto/sha512"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"hash"
	"log"
	"os"
	"path/filepath"
	"strings"
)

// C string literal of s, with octal escapes so nothing runs into the next
// character. A C99 compiler only has to take 4095 characters in one.
func lit(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '?':
			b.WriteString(`\077`)
		case c >= ' ' && c <= '~':
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	if b.Len() > 4095+2 {
		log.Fatalf("literal of %d characters is too long", b.Len()-2)
	}
	return b.String()
}

func unhex(s string) []byte {
	b, err := hex.DecodeString(s)
	if err != nil {
		log.Fatalf("invalid hex %q: %v", s, err)
	}
	return b
}

// The files TestHMACWycheproof reads, in the order of its map.
var files = []struct {
	name string
	h    func() hash.Hash
}{
	{"hmac_sha1_test.json", sha1.New},
	{"hmac_sha224_test.json", sha256.New224},
	{"hmac_sha256_test.json", sha256.New},
	{"hmac_sha3_224_test.json", func() hash.Hash { return sha3.New224() }},
	{"hmac_sha3_256_test.json", func() hash.Hash { return sha3.New256() }},
	{"hmac_sha3_384_test.json", func() hash.Hash { return sha3.New384() }},
	{"hmac_sha3_512_test.json", func() hash.Hash { return sha3.New512() }},
	{"hmac_sha384_test.json", sha512.New384},
	{"hmac_sha512_test.json", sha512.New},
	{"hmac_sha512_224_test.json", sha512.New512_224},
	{"hmac_sha512_256_test.json", sha512.New512_256},
}

func main() {
	wycheproofDir := os.Args[1]

	var tests strings.Builder
	for _, file := range files {
		data, err := os.ReadFile(filepath.Join(wycheproofDir, file.name))
		if err != nil {
			log.Fatal(err)
		}
		var wp struct {
			TestGroups []struct {
				TagSize int `json:"tagSize"`
				Tests   []struct {
					TcId    int      `json:"tcId"`
					Comment string   `json:"comment"`
					Key     string   `json:"key"`
					Msg     string   `json:"msg"`
					Tag     string   `json:"tag"`
					Result  string   `json:"result"`
					Flags   []string `json:"flags"`
				} `json:"tests"`
			} `json:"testGroups"`
		}
		if err := json.Unmarshal(data, &wp); err != nil {
			log.Fatal(err)
		}
		for _, tg := range wp.TestGroups {
			tagSize := tg.TagSize / 8
			for _, tv := range tg.Tests {
				// wycheproof.ShouldPass with no flags that pass.
				var want bool
				switch tv.Result {
				case "valid":
					want = true
				case "invalid":
					want = false
				case "acceptable":
					log.Fatalf("%s #%d: unspecified flag: %q", file.name, tv.TcId, tv.Flags)
				default:
					log.Fatalf("%s #%d: unexpected result %q", file.name, tv.TcId, tv.Result)
				}
				hm := hmac.New(file.h, unhex(tv.Key))
				hm.Write(unhex(tv.Msg))
				computedTag := hm.Sum(nil)[:tagSize]
				if got := bytes.Equal(unhex(tv.Tag), computedTag); got != want {
					log.Fatalf("%s #%d: Go's HMAC gives %v, want %v", file.name, tv.TcId, got, want)
				}
				fmt.Fprintf(&tests, "    {%s, %d, %s, %s, %s, %s, %d, %v},\n", lit(file.name),
					tv.TcId, lit(tv.Comment), lit(tv.Key), lit(tv.Msg), lit(tv.Tag), tg.TagSize, want)
			}
		}
	}
	fmt.Println("/* The Wycheproof tests: the file, the tcId, the comment, the key, the")
	fmt.Println(" * message and the tag in hex, the tag size in bits, and whether the tag is")
	fmt.Println(" * valid. */")
	fmt.Println("static const GenWycheproof gen_wycheproof[] = {")
	fmt.Print(tests.String())
	fmt.Println("};")
}
GO

{
	cat <<EOF
/* Generated by tools/gen-hmac-tests.sh; do not edit.
 *
 * The Wycheproof vectors Go's crypto/hmac tests read, from $(go env GOVERSION)
 * and github.com/c2sp/wycheproof at $wycheproof_version. */

#ifndef BURROW_TESTS_HMAC_TEST_GEN_H
#define BURROW_TESTS_HMAC_TEST_GEN_H

#include <stdbool.h>

typedef struct {
    const char *file;
    int tc_id;
    const char *comment;
    const char *key, *msg, *tag;
    int tag_size;
    bool want;
} GenWycheproof;

EOF
	(cd "$tmp/gen" && GO111MODULE=off go run main.go "$wycheproof_dir/testvectors_v1")
	cat <<'EOF'

#endif /* BURROW_TESTS_HMAC_TEST_GEN_H */
EOF
} >"$tmp/out.h"
mv "$tmp/out.h" "$out"
