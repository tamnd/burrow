/* What the lookups hand back is the caller's to change. Go appends "junk" to
 * each string, and here the bytes are written over, which is what would show
 * if they were the cache's own. */
static void spoil(Slice s) {
    for (Int i = 0; i < s.len; i++) {
        Str x = ((const Str *)s.p)[i];
        memset((void *)(uintptr_t)x.p, 'j', (size_t)x.len);
    }
}

static void TestHostCacheModification(TestingT *t) {
    /* See https://golang.org/issues/14212. */
    Arena ar;
    arena_init(&ar, NULL, 0);
    Alloc *a = arena_allocator(&ar);
    Str dir = write_testdata(t, a);
    if (dir.len == 0) {
        arena_free(&ar);
        return;
    }
    burrow__net_set_hosts_file_path(td(a, dir, "ipv4-hosts"));
    StaticHostEntry ent = {"localhost", {"127.0.0.1", "127.0.0.2", "127.0.0.3"}, 3};
    test_static_host(t, a, "ipv4-hosts", &ent);
    Str canonical;
    spoil(burrow__net_lookup_static_host(a, str_from_cstr(ent.in), &canonical));
    test_static_host(t, a, "ipv4-hosts", &ent);

    burrow__net_set_hosts_file_path(td(a, dir, "ipv6-hosts"));
    StaticHostEntry ent6 = {"::1", {"localhost"}, 1};
    test_static_addr(t, a, "ipv6-hosts", &ent6);
    spoil(burrow__net_lookup_static_addr(a, str_from_cstr(ent6.in)));
    test_static_addr(t, a, "ipv6-hosts", &ent6);

    burrow__net_set_hosts_file_path(BURROW_STR_EMPTY);
    (void)os_remove_all(dir);
    arena_free(&ar);
}

