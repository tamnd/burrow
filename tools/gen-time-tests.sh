		}
	}
	w("};\n\n")

	// Sub, Compare and friends.
	type sc struct{ s, ns int64 }
	subs := []sc{{0, 0}, {0, 1}, {1, 0}, {-1, 999999999}, {1e9, 5}, {-62135596800, 0}, {253402300799, 999999999}, {9223372036, 854775807}, {9223372036, 854775808}, {-9223372036, -854775808}, {-9223372036, -854775809}, {1e11, 0}, {-1e11, 0}}
	w("static const SCase g_subs[] = {\n")
	for _, a := range subs {
		for _, b := range subs {
			ta, tb := Unix(a.s, a.ns), Unix(b.s, b.ns)
			w("    {%s, %s, %s, %s, %s, %d},\n", i64(a.s), i64(a.ns), i64(b.s), i64(b.ns), i64(int64(ta.Sub(tb))), ta.Compare(tb))
		}
	}
	w("};\n\n")

	// Add, which saturates nothing and carries.
	w("static const AddCase g_add[] = {\n")
	for _, a := range subs {
		for _, d := range []Duration{0, 1, -1, 999999999, 1e9, -1e9, 1<<63 - 1, -1 << 63, 36 * Hour} {
			tm := Unix(a.s, a.ns).Add(d)
			w("    {%s, %s, %s, %s, %d},\n", i64(a.s), i64(a.ns), i64(int64(d)), i64(tm.Unix()), tm.Nanosecond())
		}
	}
	w("};\n\n")

	// The Duration methods.
	ds := []Duration{0, 1, -1, 999, 1000, 1500 * Millisecond, -1500 * Millisecond, 3*Hour + 25*Minute + 45*Second + 500*Millisecond, 1<<63 - 1, -1 << 63, -1<<63 + 1, 1e18, -1e18, 1e15 + 1}
	ms := []Duration{0, -1, 1, 2, 3, 1000, Second, Minute, Hour, 7 * Millisecond, 1<<63 - 1, 3e18}
	w("static const DurCase g_durs[] = {\n")
	for _, d := range ds {
		w("    {%s, %s, %s, %s, %s, %s, %s, %s},\n", i64(int64(d)), i64(d.Nanoseconds()), i64(d.Microseconds()), i64(d.Milliseconds()),
