#!/bin/sh
# Regenerates the constants of debug/dwarf, and the names their String methods
# give, from the Go sources:
#
#   - include/burrow/debug/dwarf_const.h, the Attr and Tag constants out of
#     src/debug/dwarf/const.go;
#   - src/debug/dwarf_string.c, the names Attr.String and Tag.String look up,
#     which stringer writes for Go into attr_string.go and tag_string.go.
#
# The C names are the ones tools/burrow-coverage expects, since it is loaded to
# spell them. GOROOT says which Go to read, and defaults to what go env says.
#
# Copyright 2026 The burrow Authors. All rights reserved.
# Use of this source code is governed by a BSD-style licence that can be found
# in the LICENSE file.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
goroot=${GOROOT:-$(go env GOROOT)}

python3 - "$root" "$goroot" <<'PY'
import importlib.machinery
import importlib.util
import os
import re
import sys

root, goroot = sys.argv[1], sys.argv[2]
gover = open(os.path.join(goroot, "VERSION")).readline().strip()

loader = importlib.machinery.SourceFileLoader("burrow_coverage", os.path.join(root, "tools", "burrow-coverage"))
spec = importlib.util.spec_from_loader("burrow_coverage", loader)
cov = importlib.util.module_from_spec(spec)
loader.exec_module(cov)

LICENCE = """ * Copyright 2009 The Go Authors. All rights reserved.
 * Copyright 2026 The burrow Authors. All rights reserved.
 * Use of this source code is governed by a BSD-style licence that can be found
 * in the LICENSE file. */
"""


def const_name(pkg, name):
    d = cov.Decl(pkg, "const " + name)
    cov.map_decl(d)
    return d.cname


def const_block(src, typ):
    """The lines of the const block after type typ, as (name, value, comment)
    for a constant and (None, None, comment) for a comment of its own."""
    m = re.search(r"^type %s \w+\n\nconst \(\n(.*?)^\)" % typ, src, re.S | re.M)
    if m is None:
        sys.exit("no const block for " + typ)
    out = []
    for line in m.group(1).split("\n"):
        line = line.strip()
        if not line:
            continue
        if line.startswith("//"):
            out.append((None, None, line[2:].strip()))
            continue
        cm = re.match(r"^(\w+)\s+%s\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*(?://\s*(.*))?$" % typ, line)
        if cm is None:
            sys.exit("cannot read: " + line)
        out.append((cm.group(1), int(cm.group(2), 0), cm.group(3)))
    return out


def enum(pkg, block, prefix):
    lines = ["enum {"]
    for name, val, comment in block:
        if name is None:
            lines.append("    /* %s */" % comment)
            continue
        text = "    %s = 0x%02X," % (const_name(pkg, name), val)
        if comment:
            text += " /* %s */" % comment
        lines.append(text)
    lines.append("};")
    return "\n".join(lines)


def names(block, prefix, cname):
    seen = {}
    for name, val, _ in block:
        if name is None or val in seen:
            continue
        seen[val] = name[len(prefix):]
    rows = ["static const DwarfName %s[] = {" % cname]
    for val in sorted(seen):
        rows.append('    {0x%02X, BURROW_S_INIT("%s")},' % (val, seen[val]))
    rows.append("};")
    return "\n".join(rows)


def write(path, text):
    with open(os.path.join(root, path), "w") as f:
        f.write(text)


src = open(os.path.join(goroot, "src", "debug", "dwarf", "const.go")).read()
attrs = const_block(src, "Attr")
tags = const_block(src, "Tag")

write("include/burrow/debug/dwarf_const.h", """/* Derived from Go's src/debug/dwarf/const.go.
 * Go source: %s.
 *
 * Generated by tools/gen-debug-consts.sh from the Go source. Do not edit.
 *
 * The attribute and tag constants of debug/dwarf, which burrow/debug/dwarf.h
 * includes. They are plain enums, because every value fits in an int, and the
 * DwarfAttr and DwarfTag fields that hold them are uint32_t as in Go.
 *
%s
#ifndef BURROW_DEBUG_DWARF_CONST_H
#define BURROW_DEBUG_DWARF_CONST_H

/* dwarf.Attr's constants. */
%s

/* dwarf.Tag's constants. */
%s

#endif
""" % (gover, LICENCE, enum("debug/dwarf", attrs, "Attr"), enum("debug/dwarf", tags, "Tag")))

write("src/debug/dwarf_string.c", """/* Derived from Go's src/debug/dwarf/attr_string.go and tag_string.go.
 * Go source: %s.
 *
 * Generated by tools/gen-debug-consts.sh from src/debug/dwarf/const.go. Do
 * not edit.
 *
 * The names Attr.String and Tag.String give, without the Attr and Tag in
 * front, in order of value so that a lookup can halve the table each step.
 *
%s
#include "dwarf_internal.h"

%s

%s

static Str dwarf_name_find(const DwarfName *t, Int n, uint32_t v) {
    Int lo = 0;
    Int hi = n;
    while (lo < hi) {
        Int mid = lo + (hi - lo) / 2;
        if (t[mid].v < v)
            lo = mid + 1;
        else
            hi = mid;
    }
    if (lo < n && t[lo].v == v)
        return t[lo].name;
    return BURROW_STR_EMPTY;
}

Str burrow__dwarf_attr_name(DwarfAttr a) {
    return dwarf_name_find(dwarf_attr_names,
                           (Int)(sizeof dwarf_attr_names / sizeof dwarf_attr_names[0]), a);
}

Str burrow__dwarf_tag_name(DwarfTag t) {
    return dwarf_name_find(dwarf_tag_names,
                           (Int)(sizeof dwarf_tag_names / sizeof dwarf_tag_names[0]), t);
}
""" % (gover, LICENCE, names(attrs, "Attr", "dwarf_attr_names"), names(tags, "Tag", "dwarf_tag_names")))
PY

for f in include/burrow/debug/dwarf_const.h src/debug/dwarf_string.c; do
	if command -v clang-format >/dev/null 2>&1; then
		clang-format -i "$root/$f"
	fi
done
